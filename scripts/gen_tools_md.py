"""Generate docs/TOOLS.md from the MCP tool-schema snapshots (tests/contract/snapshots), so the doc can never
drift from the real tool signatures."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SNAP = ROOT / "tests" / "contract" / "snapshots"

AUTH = {
    "portfolio": "HTTP: GigBid JWT bearer (tenant = persona claim); stdio: local user",
    "marketplace": "HTTP: GigBid JWT bearer (user, persona, trace); per-user rate limit; audit log",
    "workspace": "HTTP: GigBid JWT bearer; audit log",
}
OWNER = {"portfolio": "mcp_servers/portfolio", "marketplace": "mcp_servers/marketplace", "workspace": "mcp_servers/workspace"}
AGENTS: dict[str, list[str]] = {}


def main() -> None:
    import yaml

    cfg = yaml.safe_load((ROOT / "agent" / "config.yaml").read_text(encoding="utf-8"))
    for agent, tools in (cfg.get("tool_allowlists") or {}).items():
        for t in tools or []:
            AGENTS.setdefault(t, []).append(agent)
    lines = ["# MCP tool inventory", "",
             "Generated by `python -m scripts.gen_tools_md` from `tests/contract/snapshots/*.json` (the contract test fails CI",
             "if a signature changes unintentionally). `Agents` = per-agent allowlist in `agent/config.yaml` (A6).", "",
             "| Tool | Server | Read / write | Annotations | Required args | Auth | Agents allowed |",
             "|---|---|---|---|---|---|---|"]
    for server in ("portfolio", "marketplace", "workspace"):
        for t in json.loads((SNAP / f"{server}.json").read_text(encoding="utf-8")):
            a = t.get("annotations") or {}
            rw = "read" if a.get("readOnlyHint") else ("write (destructive)" if a.get("destructiveHint") else "write")
            ann = ", ".join(f"{k}={str(v).lower()}" for k, v in sorted(a.items()) if k.endswith("Hint"))
            req = ", ".join(t["input"].get("required", [])) or "-"
            lines.append(f"| `{t['name']}` | {server} | {rw} | {ann} | {req} | {AUTH[server]} | {', '.join(AGENTS.get(server + '.' + t['name'], [])) or '-'} |")
    lines += [
        "", "## Write-tool guarantees (marketplace)", "",
        "* `idempotency_key` (16-128 chars) on every write; the first response is stored per (user, tool, key) and replayed on retry,",
        "  and the same key is forwarded to GigSim - a retried call never submits twice or spends Connects twice.",
        "* `dry_run=true` returns exactly what would be sent (payload) and its Connects cost / balance after; the approval screen shows it.",
        "* Every call (read and write) is appended to `mcp_audit_log` (user, tool, PII-masked args and result, status, trace id);",
        "  a database trigger rejects UPDATE and DELETE.",
        "* In live Upwork mode `submit_proposal` never submits: the draft waits for the user's confirmation on Upwork.",
        "", "## Third-party MCP servers (A5)", "",
        "| Server | Used for | Transport / auth | One-line trust rationale |", "|---|---|---|---|",
        "| Upwork official MCP (`https://mcp.upwork.com/mcp`) | live marketplace adapter: job search, proposal/message **drafts** | Streamable HTTP, OAuth 2.1 + PKCE, tokens Fernet-encrypted per user | First-party server operated by the marketplace itself; every write is a draft the user confirms on Upwork, so GigBid can never send on its own. |",
        "| GitHub official MCP (`github/github-mcp-server`) | ingesting the user's repos (README + code) into the portfolio (B1) | Streamable HTTP, fine-grained read-only PAT, `X-MCP-Readonly` | Maintained by GitHub; we enable read-only mode with a token scoped to public repo contents, so it cannot modify anything. |",
    ]
    (ROOT / "docs" / "TOOLS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote docs/TOOLS.md")


if __name__ == "__main__":
    main()
