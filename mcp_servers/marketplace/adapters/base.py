"""Adapter contract behind the Marketplace MCP server. GigSim and live Upwork both implement it, so the
graph (which only sees MCP tools) cannot tell which marketplace it is talking to (R1, A4)."""

from __future__ import annotations

from typing import Any, Protocol


class MarketplaceError(Exception):
    def __init__(self, kind: str, message: str, retry_after: float | None = None, status: int | None = None) -> None:
        super().__init__(f"{kind}: {message}")
        self.kind = kind                # unavailable | rate_limited | not_found | policy | insufficient_connects | invalid | auth
        self.message = message
        self.retry_after = retry_after
        self.status = status


class MarketplaceAdapter(Protocol):
    name: str

    async def search_jobs(self, query: str, category: str | None, skills: list[str] | None, min_budget: float | None,
                          since_minutes: int | None, limit: int) -> list[dict[str, Any]]: ...
    async def get_job(self, job_id: str) -> dict[str, Any]: ...
    async def get_client_history(self, client_id: str) -> dict[str, Any]: ...
    async def get_connects_balance(self) -> dict[str, Any]: ...
    async def get_market_stats(self, category: str) -> dict[str, Any]: ...
    async def get_policy(self) -> dict[str, Any]: ...
    async def list_threads(self) -> list[dict[str, Any]]: ...
    async def list_messages(self, thread_id: str) -> list[dict[str, Any]]: ...
    async def list_events(self, since: int) -> list[dict[str, Any]]: ...
    async def list_proposals(self) -> list[dict[str, Any]]: ...
    async def create_proposal_draft(self, payload: dict[str, Any], idempotency_key: str) -> dict[str, Any]: ...
    async def submit_proposal(self, proposal_id: str, idempotency_key: str) -> dict[str, Any]: ...
    async def send_message(self, thread_id: str, text: str, slots: list[dict] | None, idempotency_key: str) -> dict[str, Any]: ...
    async def health(self) -> dict[str, Any]: ...
